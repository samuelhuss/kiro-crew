function generateManualPhaseTemplate(phase: MigrationPlanPhase, _req: MigrationRequirements): string {
  const steps = phase.actions.map((a, i) =>
    `#   ${i + 1}. ${a.description}\n#      Validation: ${a.validationSteps.join(', ')}`
  ).join('\n');

  return `AWSTemplateFormatVersion: '2010-09-09'
Description: >-
  Migration Phase ${phase.order}: ${phase.name} (MANUAL STEPS - no CFN resources)
  This phase requires manual intervention. Follow the steps below.

# ═══════════════════════════════════════════════════════════════════
# MANUAL STEPS for Phase ${phase.order}: ${phase.name}
# ═══════════════════════════════════════════════════════════════════
#
${steps}
#
# ═══════════════════════════════════════════════════════════════════

Resources:
  # Placeholder - CFN requires at least one resource
  WaitConditionHandle:
    Type: AWS::CloudFormation::WaitConditionHandle

Outputs:
  PhaseStatus:
    Description: Manual phase - verify steps above are complete
    Value: 'MANUAL_STEPS_REQUIRED'
`;
}

// ── Output generators ────────────────────────────────────────────────────────

function generateOutputBlock(action: MigrationAction): string {
  const id = sanitizeLogicalId(action.resourceName || action.resourceId);
  return `  ${id}Output:
    Description: '${action.resourceType} - ${action.resourceName}'
    Value: !Ref ${id}
    Export:
      Name: !Sub '\${AWS::StackName}-${id}'`;
}

// ── Helpers ──────────────────────────────────────────────────────────────────

function sanitizeLogicalId(name: string): string {
  // CFN logical IDs: alphanumeric only, start with letter
  return name
    .replace(/[^a-zA-Z0-9]/g, '')
    .replace(/^[^a-zA-Z]/, 'R')
    .slice(0, 64) || 'Resource';
}
