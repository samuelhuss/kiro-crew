export interface GeneratedTemplate {
  stackName: string;
  templatePath: string;
  yaml: string;
}

/**
 * Generate CloudFormation templates for each phase in the plan.
 */
export function generateCfnTemplates(plan: MigrationPlan): GeneratedTemplate[] {
  const templates: GeneratedTemplate[] = [];

  for (const phase of plan.phases) {
    for (const stack of phase.cfnStacks) {
      const yaml = generatePhaseTemplate(phase, plan.requirements);
      templates.push({
        stackName: stack.stackName,
        templatePath: stack.templatePath,
        yaml,
      });
    }
  }

  return templates;
}

function generatePhaseTemplate(
  phase: MigrationPlanPhase,
  requirements: MigrationRequirements
): string {
  const resources: string[] = [];
  const outputs: string[] = [];

  for (const action of phase.actions) {
    if (action.actionType === 'CUTOVER_DNS' || action.actionType === 'DECOMMISSION_SOURCE') {
      continue; // These are manual, not CFN-managed
    }
    if (action.actionType === 'VALIDATE') {
      continue; // Validation is not a CFN resource
    }

    const cfnResource = generateResourceBlock(action, requirements);
    if (cfnResource) {
      resources.push(cfnResource);
      outputs.push(generateOutputBlock(action));
    }
  }

  // If phase has no CFN-manageable resources, produce a comment-only template
  if (resources.length === 0) {
    return generateManualPhaseTemplate(phase, requirements);
  }

  return `AWSTemplateFormatVersion: '2010-09-09'
Description: >-
  Migration Phase ${phase.order}: ${phase.name}
  Generated by aws-migration-mvp planner.
  ${phase.actions.length} actions, estimated ${phase.estimatedDurationMinutes} minutes.

Parameters:
  Environment:
    Type: String
    Default: migration
    Description: Deployment environment tag

  SourceRegion:
    Type: String
    Default: ${requirements.sourceRegion}
    Description: Source AWS region

  TargetVpcId:
    Type: AWS::EC2::VPC::Id
    Description: VPC ID in the target region (create networking phase first)

  TargetSubnetIds:
    Type: List<AWS::EC2::Subnet::Id>
    Description: Subnet IDs in the target VPC

Resources:
${resources.join('\n\n')}

Outputs:
${outputs.join('\n\n')}
`;
}

function generateResourceBlock(action: MigrationAction, requirements: MigrationRequirements): string | null {
  const logicalId = sanitizeLogicalId(action.resourceName || action.resourceId);
  const cfnType = RESOURCE_TYPE_TO_CFN[action.resourceType];

  if (!cfnType) return null;

  switch (action.resourceType) {
    case 'AWS::EC2::VPC':
      return generateVpcResource(logicalId, action);
    case 'AWS::EC2::Subnet':
      return generateSubnetResource(logicalId, action);
    case 'AWS::EC2::SecurityGroup':
      return generateSecurityGroupResource(logicalId, action);
    case 'AWS::EC2::Instance':
      return generateEc2Resource(logicalId, action);
    case 'AWS::RDS::DBInstance':
      return generateRdsResource(logicalId, action, requirements);
    case 'AWS::S3::Bucket':
      return generateS3Resource(logicalId, action);
    case 'AWS::Lambda::Function':
      return generateLambdaResource(logicalId, action);
    case 'AWS::DynamoDB::Table':
      return generateDynamoDbResource(logicalId, action);
    case 'AWS::ECS::Cluster':
      return generateEcsClusterResource(logicalId, action);
    case 'AWS::SQS::Queue':
      return generateSqsResource(logicalId, action);
    case 'AWS::SNS::Topic':
      return generateSnsResource(logicalId, action);
    default:
      return generateGenericResource(logicalId, action, cfnType);
  }
}

