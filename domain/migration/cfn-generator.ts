function generateVpcResource(id: string, action: MigrationAction): string {
  return `  ${id}:
    Type: AWS::EC2::VPC
    Properties:
      CidrBlock: '10.0.0.0/16' # TODO: adjust CIDR for target
      EnableDnsHostnames: true
      EnableDnsSupport: true
      Tags:
        - Key: Name
          Value: ${action.resourceName}-migrated
        - Key: MigrationSource
          Value: ${action.resourceId}
        - Key: Environment
          Value: !Ref Environment`;
}

